function Robot = CreateIRB1200(name, tool_length, tool_height, tool_angle)
t_h = tool_height;
t_l = tool_length + 0.082;
L(1) = Link([0 0 0 0 0], 'modified');
L(1).qlim = [-17*pi/18,17*pi/18];
L(2) = Link([0 0 0 -pi/2 0], 'modified');
L(2).offset = -pi/2;
L(2).qlim = [-5*pi/9,13*pi/18];
L(3) = Link([0 0 0.448 0 0], 'modified');
L(3).qlim = [-10*pi/9,7*pi/18];
L(4) = Link([0 0.451 0.042 -pi/2 0], 'modified');
L(4).qlim = [-3*pi/2,3*pi/2];
L(5) = Link([0 0 0 pi/2 0], 'modified');
L(5).qlim = [-13*pi/18,13*pi/18];
L(6) = Link([0 0 0 -pi/2 0], 'modified');
L(6).qlim = [-242*pi/180,242*pi/180];
L(6).offset = pi;
Robot = SerialLink(L, 'name', name);
Robot.base = transl(0, 0, 0.3991);
Robot.tool = transl(t_h, 0, t_l)*troty(tool_angle);